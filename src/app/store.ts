export interface ViewSettings {
  texture: boolean;
  wireframe: boolean;
  clay: boolean;
  autoRotate: boolean;
  darkBackground: boolean;
  showDepth: boolean;
}

export interface ResultInfo {
  driverId: string;
  kind: 'depth' | 'geometry' | 'model';
  stats: MeshStats;
  /** Grayscale preview of the depth map (depth results only). */
  depthPreview: RGBAImage | null;
  elapsedMs: number;
  sourceName: string;
  /** Multi-view fusion's consistency report (null for other drivers). */
  fusion: FusionReport | null;
  /** Views present but switched off (trust 'off') when the fusion ran; the report itself skips them. */
  fusionOff?: OtherViewId[];
}

/** The views besides the front (the front is always the source image). */
export type OtherViewId = Exclude<ViewId, 'front'>;
export const OTHER_VIEWS: OtherViewId[] = ['back', 'left', 'right', 'top', 'bottom'];

/** An extra view of the subject: uploaded or generated by AI. */
export interface ViewEntry {
  /** The file / AI output the image was decoded from (cloud drivers upload it). */
  file: Blob;
  /** Working image (longest side ≤ WORKING_MAX_SIDE). */
  image: RGBAImage;
  /** Foreground mask (alpha, plain border or AI removal); null = whole image. */
  mask: Mask | null;
  origin: 'upload' | 'ai';
  name: string;
  /** Alignment to the front (auto / manual offset, scale, flip) and what the view is trusted for. */
  align: ViewAlign;
}

export type ViewEntries = Partial<Record<OtherViewId, ViewEntry>>;

/** 'enhance': image enhancement (AI super-resolution or a local enhancer). */
export type AiJobKind = 'prep' | 'views' | 'enhance';

/** The AI job in flight (one at a time). */
export interface AiJob {
  kind: AiJobKind;
  /** Views jobs: the view being made, or 'all' for "generate the missing views". */
  target: OtherViewId | 'all' | null;
  progress: Progress | null;
}

/** An enhanced front image awaiting Apply / Discard. */
export interface EnhancePending {
  /** The new source (working image, texture copy, encoded file). */
  source: SourceImage;
  /** The front it was made from (Apply only while that is still the front). */
  from: SourceImage;
  preset: EnhancePresetId;
  /** What actually ran (the local fallback's plan when the AI could not run). */
  plan: EnhancePlan;
  /** The automatic preset fell back to the local upscaler (the AI model could not run). */
  fallback: I18nText | null;
  elapsedMs: number;
}

/** The enhancement in use: `after` is the front, `before` comes back with Revert. */
export interface EnhanceApplied {
  before: SourceImage;
  after: SourceImage;
  preset: EnhancePresetId;
}

/** Human analysis of one image: running, or its result. */
export interface HumanState {
  image: RGBAImage;
  analysis: HumanAnalysis | 'analyzing';
}

